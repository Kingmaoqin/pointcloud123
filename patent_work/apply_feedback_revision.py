# ---------------------------------------------------------------- 工具函数

def find_para(doc, prefix: str) -> int:
    for i, p in enumerate(doc.paragraphs):
        if p.text.strip().startswith(prefix):
            return i
    raise ValueError(f"paragraph not found: {prefix!r}")


def insert_paragraph_after(paragraph: Paragraph, text: str) -> Paragraph:
    """复制 paragraph 的段落/字符格式，插入一个新段落，写入 text。"""
    new_p = copy.deepcopy(paragraph._p)
    paragraph._p.addnext(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    _set_single_run_text(new_para, text)
    return new_para


def _set_single_run_text(paragraph: Paragraph, text: str) -> None:
    runs = paragraph.runs
    if not runs:
        paragraph.add_run(text)
        return
    runs[0].text = text
    for extra in runs[1:]:
        extra.text = ""


def replace_paragraph_text(paragraph: Paragraph, text: str) -> None:
    _set_single_run_text(paragraph, text)


def remove_paragraph(paragraph: Paragraph) -> None:
    paragraph._p.getparent().remove(paragraph._p)


