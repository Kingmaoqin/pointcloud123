def _fit_to_canvas(src_png: Path, size: tuple[int, int]) -> bytes:
    """等比缩放后白底居中补边到原尺寸，使docx中固定的显示尺寸不产生拉伸变形。"""
    from PIL import Image

    im = Image.open(src_png).convert("RGB")
    tw, th = size
    scale = min(tw / im.width, th / im.height)
    im = im.resize((max(int(im.width * scale), 1), max(int(im.height * scale), 1)),
                   Image.LANCZOS)
    canvas = Image.new("RGB", (tw, th), "white")
    canvas.paste(im, ((tw - im.width) // 2, (th - im.height) // 2))
    buf = io.BytesIO()
    canvas.save(buf, format="PNG")
    return buf.getvalue()


def replace_figures(docx_path: Path) -> None:
    """按 2026-07-28 批注6/7/8/9 用重画的图4、图5、图8 替换docx中的对应附图。"""
    from PIL import Image

    with zipfile.ZipFile(docx_path) as zin:
        items = zin.infolist()
        payload = {it.filename: zin.read(it.filename) for it in items}

    for member, new_png in REDRAWN_FIGURES.items():
        if member not in payload:
            raise RuntimeError(f"{docx_path} 缺少媒体文件 {member}")
        if not new_png.exists():
            raise RuntimeError(f"重画附图不存在：{new_png}（请先运行 redraw_figures_0728.py）")
        orig_size = Image.open(io.BytesIO(payload[member])).size
        payload[member] = _fit_to_canvas(new_png, orig_size)
        print(f"[figure] replaced {member} <- {new_png.name} @{orig_size[0]}x{orig_size[1]}")

    tmp = docx_path.with_suffix(".tmp.docx")
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
        for it in items:
            zout.writestr(it, payload[it.filename])
    tmp.replace(docx_path)
    print(f"[figure] rewrote -> {docx_path}")


